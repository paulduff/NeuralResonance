"""Generate namespace-only parity for ordered routed muscle geometry."""
import argparse
from hashlib import sha256
from pathlib import Path

def generate(root):
    source=(root/'src/NRE.SimAvatar/AvatarRoutedMusclePath.cs').read_text(encoding='utf-8-sig')
    assert source.count('namespace NRE.SimAvatar\n')==1
    return ('// Generated by tools/prepare-unity-routed-path.py; do not edit.\n'
        '// Canonical UTF-8/LF SHA256: '+sha256(source.encode()).hexdigest().upper()+'\n'+source.replace('namespace NRE.SimAvatar\n','namespace Nre.UnityWorld\n'))

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--repository',type=Path,default=Path(__file__).resolve().parents[1]);a=p.parse_args()
    (a.repository/'UnityWorld/Assets/NRE/Runtime/RoutedMusclePathGeometry.cs').write_text(generate(a.repository),encoding='utf-8',newline='\n')
