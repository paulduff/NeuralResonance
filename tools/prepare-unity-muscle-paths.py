"""Generate the isolated Unity geometry core, changing only its namespace."""
import argparse
from hashlib import sha256
from pathlib import Path


def generate(root):
    source = (root / 'src/NRE.SimAvatar/AvatarMusclePath.cs').read_text(encoding='utf-8-sig')
    assert source.count('namespace NRE.SimAvatar\n') == 1
    header = '// Generated by tools/prepare-unity-muscle-paths.py; do not edit.\n'
    header += '// Canonical UTF-8/LF SHA256: ' + sha256(source.encode('utf-8')).hexdigest().upper() + '\n'
    return header + source.replace('namespace NRE.SimAvatar\n', 'namespace Nre.UnityWorld\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--repository', type=Path, default=Path(__file__).resolve().parents[1])
    args = parser.parse_args(); root = args.repository.resolve()
    (root / 'UnityWorld/Assets/NRE/Runtime/MusclePathGeometry.cs').write_text(generate(root), encoding='utf-8', newline='\n')
